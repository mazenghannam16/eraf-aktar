class QuizCategory {
  final String id, title, subtitle;
  final int color, symbol;
  const QuizCategory(
    this.id,
    this.title,
    this.subtitle,
    this.color,
    this.symbol,
  );
}

class Question {
  final String id, category, text, explanation;
  final List<String> options;
  final int correct;
  const Question(
    this.id,
    this.category,
    this.text,
    this.options,
    this.correct,
    this.explanation,
  );
}

class Fact {
  final String id, category, title, body, source;
  const Fact(this.id, this.category, this.title, this.body, this.source);
}

